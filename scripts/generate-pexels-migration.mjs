// Pexels migration generator.
//
// Reads scripts/catalogue-data/pexels-map.json (written by
// fetch-pexels-images.mjs) and emits a SQL migration that replaces the
// generated SVG tile URLs in public.product_images with the matched Pexels
// photo URLs. Products without a match are left untouched so they keep their
// SVG fallback.
//
// Usage:
//   node scripts/generate-pexels-migration.mjs [--name 20260816010000]
//
// Prints the migration to stdout. Pipe it into a file, e.g.:
//   node scripts/generate-pexels-migration.mjs > supabase/migrations/20260816010000_pexels_product_images.sql

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = `${__dirname}/..`;

const args = process.argv.slice(2);
const nameArg = args.find((a) => a.startsWith("--name="));
const fileName = nameArg ? nameArg.split("=")[1] : "20260816010000_pexels_product_images.sql";

const map = JSON.parse(
  readFileSync(join(root, "scripts/catalogue-data/pexels-map.json"), "utf8"),
);

const entries = Object.entries(map.products).filter(([, v]) => v && v.url);
if (entries.length === 0) {
  console.error("pexels-map.json has no entries — run fetch-pexels-images.mjs first.");
  process.exit(1);
}

function sq(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const rows = entries
  .map(([slug, v]) => `  (${sq(slug)}, ${sq(v.url)}, ${sq(v.alt ?? v.name ?? slug)})`)
  .join(",\n");

const sql = `-- Generated by scripts/generate-pexels-migration.mjs from pexels-map.json (${new Date().toISOString()})
-- Replaces generated SVG product tiles with real Pexels photos.
-- Products without a Pexels match keep their existing SVG image.

update public.product_images pi
set url = v.url,
    alt_text = v.alt
from (
  values
${rows}
) as v(slug, url, alt)
join public.products p on p.slug = v.slug
where pi.product_id = p.id
  and pi.variant_id is null;

-- Safety: fail loudly if any product in the map is missing a primary image row.
do $$
declare
  missing integer;
begin
  select count(*) into missing
  from (
    values
${rows}
  ) as v(slug, url, alt)
  where not exists (
    select 1
    from public.products p
    join public.product_images pi on pi.product_id = p.id and pi.variant_id is null
    where p.slug = v.slug
  );
  if missing > 0 then
    raise exception '% mapped product(s) have no primary image row — fix before applying', missing;
  end if;
end $$;

-- Pexels attribution is appreciated, not required; the URLs above are stable
-- CDN links served under images.pexels.com (already allowlisted).
`;

console.log(sql);
console.log(`-- ${entries.length} product images updated. Apply as ${fileName}`);