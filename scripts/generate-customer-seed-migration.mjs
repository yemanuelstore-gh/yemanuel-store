// Historical customer seed migration generator.
//
// Reads the validated dataset (scripts/customer-data/customers.json, exactly
// 9,847 customers) and emits the idempotent seed migration:
//
//   supabase/migrations/20260817050000_historical_customers.sql
//
// Migration guarantees:
//   - customers.created_by resolves to the Owner staff record (YS-OWNER-0001).
//   - Historical created_at / updated_at timestamps are preserved.
//   - Seed rows colliding with an EXISTING customer (customer_code, email, or
//     digit-normalised phone) are skipped, so the live owner record
//     (CUS-FAABDD14, Sikapa Barima) is never duplicated or altered.
//   - One default billing+delivery address is inserted per customer.
//   - Safe to re-run (guards + unique email index; phone has no unique index
//     so the explicit collision guard carries that responsibility).
//
// Run: node scripts/generate-customer-seed-migration.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = `${__dirname}/..`;
const dataDir = `${root}/scripts/customer-data`;
const migrationPath = `${root}/supabase/migrations/20260817050000_historical_customers.sql`;

const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sqlOrNull = (v) => (v === null || v === undefined || v === "" ? "NULL" : sql(v));

const dataset = JSON.parse(readFileSync(`${dataDir}/customers.json`, "utf8"));
const customers = dataset.customers;

if (customers.length !== 9847) {
  throw new Error(`Expected 9,847 customers, found ${customers.length}. Refusing to generate.`);
}

const rows = customers.map((c) => {
  const dbType = c.customerType === "corporate" ? "business" : c.customerType;
  return `  (${sql(c.customerCode)}, ${sql(dbType)}, ${sql(c.firstName)}, ${sql(c.lastName)}, ${sqlOrNull(c.businessName)}, ${sql(c.phone)}, ${sqlOrNull(c.email)}, ${sqlOrNull(c.tinNumber)}, ${sql(c.status)}, ${sqlOrNull(c.notes)}, ${sql(c.createdAt)}, ${sql(c.address.label)}, ${sql(c.address.recipientName)}, ${sql(c.address.recipientPhone)}, ${sql(c.address.addressLine1)}, ${sqlOrNull(c.address.addressLine2)}, ${sql(c.address.city)}, ${sql(c.address.regionCode)}, ${sqlOrNull(c.address.postalCode)}, ${c.address.isDefaultBilling}, ${c.address.isDefaultDelivery})`;
});

const header = `-- Historical customer master dataset for Yemanuel Store.
--
-- Generated by scripts/generate-customer-seed-migration.mjs from the
-- validated dataset scripts/customer-data/customers.json (exactly 9,847
-- customers, seed 20260817). Do not edit by hand.
--
-- Scope: customers + customer_addresses ONLY. No orders, payments, purchases,
-- expenses or inventory movements are created. No spending totals or
-- customer lifetime values are fabricated.
--
-- customer_type mapping: the schema enum is ('individual', 'business'), so
-- the dataset's "corporate" type maps to 'business' at insert time (corporate
-- buyers keep their company names, TINs and notes).
--
-- Registration dates: Monday 17 January 2022 → 17 August 2026, operating
-- days only (Monday–Saturday; Sundays closed), UTC.
--
-- Idempotent and safe to re-run:
--   - created_by resolves to the Owner staff record (YS-OWNER-0001).
--   - Seed rows are skipped when customer_code, email or digit-normalised
--     phone already exists on an existing customer record (reconciles the
--     live owner record CUS-FAABDD14 — Sikapa Barima — without touching it).

set search_path = public, extensions;

create temp table seed_customers (
  customer_code       text not null,
  customer_type       public.customer_type not null,
  first_name          text not null,
  last_name           text not null,
  business_name       text,
  phone               text not null,
  email               citext,
  tin_number          text,
  status              public.customer_status not null,
  notes               text,
  created_at          timestamptz not null,
  address_label       text not null,
  recipient_name      text not null,
  recipient_phone     text not null,
  address_line_1      text not null,
  address_line_2      text,
  city_name           text not null,
  region_code         text not null,
  postal_code         text,
  is_default_billing  boolean not null,
  is_default_delivery boolean not null
);

insert into seed_customers values
${rows.join(",\n")};

-- Reconcile against existing customers: drop any seed row whose customer_code,
-- email or digit-normalised phone collides with a live record. Existing
-- records are never altered. ("0541765068" and "+233 54 176 5068" both
-- normalise to "233541765068".)
delete from seed_customers s
where exists (
  select 1
  from public.customers c
  where c.customer_code = s.customer_code
     or c.email = s.email
     or case
          when translate(c.phone, ' +-()', '') like '0%' then '233' || substr(translate(c.phone, ' +-()', ''), 2)
          else translate(c.phone, ' +-()', '')
        end =
        case
          when translate(s.phone, ' +-()', '') like '0%' then '233' || substr(translate(s.phone, ' +-()', ''), 2)
          else translate(s.phone, ' +-()', '')
        end
);

-- Sanity: the dataset must be complete unless a legitimate collision existed.
do $$
declare
  v_total integer;
  v_owner uuid;
begin
  select count(*) into v_total from seed_customers;
  select profile_id into v_owner from public.staff where employee_code = 'YS-OWNER-0001' limit 1;
  if v_owner is null then
    raise exception 'Owner staff record (YS-OWNER-0001) not found; cannot resolve created_by.';
  end if;
  if v_total < 9847 then
    raise notice 'Seed skipped % row(s) that collided with existing customers; inserting %.', 9847 - v_total, v_total;
  end if;
end $$;
`;

const body = `
-- 1. Customers -------------------------------------------------------------
insert into public.customers (
  customer_code, customer_type, first_name, last_name, business_name,
  phone, email, tin_number, status, notes, created_at, updated_at, created_by
)
select
  s.customer_code, s.customer_type, s.first_name, s.last_name, s.business_name,
  s.phone, s.email, s.tin_number, s.status, s.notes, s.created_at, s.created_at,
  o.id
from seed_customers s
cross join lateral (
  select profile_id as id
  from public.staff
  where employee_code = 'YS-OWNER-0001'
  limit 1
) o
on conflict (customer_code) do nothing;

-- 2. Customer addresses ----------------------------------------------------
insert into public.customer_addresses (
  customer_id, label, recipient_name, recipient_phone, address_line_1,
  address_line_2, city_id, region_id, postal_code, is_default_billing,
  is_default_delivery, created_at, updated_at
)
select
  c.id, s.address_label, s.recipient_name, s.recipient_phone, s.address_line_1,
  s.address_line_2, ct.id, rg.id, s.postal_code, s.is_default_billing,
  s.is_default_delivery, s.created_at, s.created_at
from seed_customers s
join public.customers c on c.customer_code = s.customer_code
join public.cities ct on ct.name = s.city_name
join public.regions rg on rg.code = s.region_code
on conflict do nothing;
`;

const footer = `
-- 3. Post-insert verification (notices only; raises on hard failures) ------
do $$
declare
  v_customers integer;
  v_addresses integer;
begin
  select count(*) into v_customers from public.customers;
  select count(*) into v_addresses from public.customer_addresses;
  raise notice 'Customers total after seed: %', v_customers;
  raise notice 'Customer addresses total after seed: %', v_addresses;

  if exists (
    select 1 from public.customers
    where extract(isodow from created_at at time zone 'UTC') = 7
  ) then
    raise exception 'Sunday-dated customer record found after seed.';
  end if;
end $$;
`;

const migration = `${header}\n${body}\n${footer}\n`;

writeFileSync(migrationPath, migration);
console.log(`Wrote ${migrationPath}`);
console.log(`  customers: ${customers.length}`);
console.log(`  addresses: ${customers.length}`);
console.log(`  size: ${(migration.length / 1024).toFixed(0)} KB`);